test('pending forks use saved history, suppress duplicates and survive store restart', t => {
  const home = fs.mkdtempSync(path.join(os.tmpdir(), 'chatsync-session-fork-'));
  t.after(() => fs.rmSync(home, { recursive: true, force: true }));
  const store = new RecoveryStore(home);
  const base = event(0, 'shared');
  const local = jsonl([header, base, event(1, 'local')]);
  const remote = jsonl([header, base, event(1, 'remote')]);
  const pair = { local, remote };
  const main = { kind: 'main', path: logPath, status: 'merged', kept: 'local' };
  const deferred = { kind: 'scope-backup', path: logPath, status: 'deferred' };
  store.save(main, { local: jsonl([header, base]), remote });
  store.save(main, { local: jsonl([header, event(2, 'broken')]), remote });
  store.save(main, { local: jsonl([{ ...header, id: 'foreign' }, event(0, 'local')]), remote });
  const future = { ...header, version: 999 };
  store.save(main, { local: jsonl([future, event(0, 'local')]), remote: jsonl([future, event(0, 'remote')]) });
  store.save({ ...main, path: 'settings.yaml' }, pair);
  store.save({ ...deferred, status: 'applied' }, pair);
  store.save({ ...main, status: 'pending' }, pair);
  assert.deepEqual(store.pendingSessionForks(), []);

  const old = store.save(main, pair);
  store.finish(old.id, { sessionFork: undefined });
  const duplicate = store.save(deferred, pair);
  assert.equal(duplicate.sessionFork, true);
  const restarted = new RecoveryStore(home);
  const forks = restarted.pendingSessionForks();
  assert.equal(forks.length, 1);
  assert.equal(forks[0].sessionId, sessionId);
  assert.ok([duplicate.id, old.id].includes(forks[0].id));

  const versions = { local: duplicate.versions.local.sha256, remote: duplicate.versions.remote.sha256 };
  assert.throws(() => restarted.archive(duplicate.id, { ...versions, remote: 'stale' }), /原件已变化/);
  restarted.archive(duplicate.id, versions);
  assert.deepEqual(restarted.pendingSessionForks(), []);
  restarted.archive(duplicate.id, null, false);
  assert.equal(restarted.pendingSessionForks().length, 1);
  restarted.finish(duplicate.id, { imports: { local: { status: 'verified', sourceHash: versions.local } } });
  assert.equal(restarted.pendingSessionForks().length, 1, 'importing the kept side does not close the fork');
  restarted.finish(duplicate.id, { imports: { remote: { status: 'verified', sourceHash: versions.remote } } });
  assert.deepEqual(new RecoveryStore(home).pendingSessionForks(), []);

  const third = store.save({ ...main, kept: 'remote' }, { local: jsonl([header, base, event(1, 'third')]), remote });
  assert.deepEqual(restarted.pendingSessionForks(), [{ id: third.id, sessionId }]);
  restarted.finish(third.id, { forkHandled: true });
  assert.deepEqual(new RecoveryStore(home).pendingSessionForks(), []);
});

test('two transport copies expose saved fork originals after later runs and restart', async t => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'chatsync-fork-transport-'));
  t.after(() => removeFixture(root));
  const remote = path.join(root, 'remote.git');
  execFileSync('git', ['init', '--bare', remote], { stdio: 'ignore' });
  const options = { remote, autoRepo: false, workspaceSync: false, minCommitIntervalSeconds: 0 };
  const make = name => {
    const home = path.join(root, name);
    fs.mkdirSync(home);
    const engine = new SyncEngine(home, options);
    engine.verifyPrivateRemote = async () => ({ ok: true });
    acceptFixturePreviews(engine);
    return engine;
  };
  const a = make('a');
  const b = make('b');
  const shared = event(0, 'shared');
  const sideA = zstdCompressSync(jsonl([header, shared, event(1, 'a')]));
  const sideB = zstdCompressSync(jsonl([header, shared, event(1, 'b')]));
  const write = (engine, bytes) => {
    const file = path.join(engine.home, logPath);
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, bytes);
  };
  const sync = engine => engine.syncOnce('fork-fixture', { forceCommit: true, offlineApply: true });
  write(a, zstdCompressSync(jsonl([header, shared])));
  assert.equal((await sync(a)).error, undefined);
  assert.equal((await sync(b)).error, undefined);
  write(a, sideA);
  write(b, sideB);
  assert.equal((await sync(a)).error, undefined);
  const merged = await sync(b);
  assert.equal(merged.error, undefined);
  assert.equal(merged.sessionWarnings?.[0]?.reason, 'divergent-session-history');
  assert.equal((await sync(b)).sessionWarnings?.length || 0, 0);
  const reopened = new SyncEngine(b.home, options).recovery;
  const [{ id }] = reopened.pendingSessionForks();
  const record = reopened.read(id);
  assert.deepEqual(reopened.version(record, 'local'), sideB);
  assert.deepEqual(reopened.version(record, 'remote'), sideA);
  b.loadRecoveryCatalog = async () => fixtureCatalog;
  write(b, zstdCompressSync(jsonl([header, shared, event(1, 'b'), event(2, 'b continued')])));
  assert.deepEqual((await compareRecoveryBranches(b, id)).currentVersions, { local: true, remote: false });

  const deferred = await sync(a);
  assert.equal(deferred.sessionDeferred?.[0]?.reason, 'divergent-session-history');
  assert.match(deferred.error, /部分内容未应用/);
  const [fork] = a.recovery.pendingSessionForks();
  assert.equal(a.recovery.read(fork.id).kind, 'scope-backup');
  assert.deepEqual(fs.readFileSync(path.join(a.home, logPath)), sideA);
});

test('keeping one conflict version preserves the live session and allows deleting the backup on demand', async t => {
  const home = fs.mkdtempSync(path.join(fs.realpathSync(os.tmpdir()), 'chatsync-fork-keep-'));
  t.after(() => removeFixture(home));
  const engine = new SyncEngine(home, { autoRepo: false, workspaceSync: false });
  engine.loadRecoveryCatalog = async () => fixtureCatalog;
  const local = jsonl([header, event(0, 'local')]);
  const remote = jsonl([header, event(0, 'remote')]);
  const live = path.join(home, logPath);
  fs.mkdirSync(path.dirname(live), { recursive: true });
  fs.writeFileSync(live, remote);
  const pair = { local, remote };
  const conflict = { kind: 'scope-backup', path: logPath, status: 'deferred' };
  const duplicate = engine.recovery.save(conflict, pair);
  const { id, versions } = engine.recovery.save(conflict, pair);
  const expectedVersions = { local: versions.local.sha256, remote: versions.remote.sha256 };
  await assert.rejects(keepCurrentConflictVersion(engine, { id, keep: 'local', expectedVersions }), /当前会话已变化/);
  await assert.rejects(previewStorageCleanup(engine, { recoveryId: id }), /不是可删除的备份/);
  await keepCurrentConflictVersion(engine, { id, keep: 'remote', expectedVersions });
  assert.deepEqual(engine.recovery.read(id).conflictResolution, { kept: 'remote', discarded: 'local' });
  assert.equal(engine.recovery.read(duplicate.id).conflictResolution, undefined);
  assert.deepEqual(engine.recovery.pendingSessionForks(), []);
  assert.deepEqual(fs.readFileSync(live), remote);
  assert.deepEqual(engine.recovery.version(engine.recovery.read(id), 'local'), local);
  const { token } = await previewStorageCleanup(engine, { recoveryId: id });
  assert.equal((await applyStorageCleanup(engine, { token, confirm: true })).ok, true);
  assert.throws(() => engine.recovery.read(id), { code: 'ENOENT' });
  assert.deepEqual(engine.recovery.pendingSessionForks(), []);
  assert.deepEqual(fs.readFileSync(live), remote);
});
